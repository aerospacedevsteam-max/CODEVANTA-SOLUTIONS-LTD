// Writes supabase/migrations/20261028000004_initial_catalogue.sql from
// scripts/catalogue.mjs and public/previews/previews.json.
// Products are seeded as 'coming_soon' (visible, NOT purchasable). They become
// purchasable only after `npm run products:upload -- --publish` has stored the
// ZIP in private storage — the database refuses to publish without the file.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { categories, products } from './catalogue.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const previews = JSON.parse(readFileSync(join(root, 'public', 'previews', 'previews.json'), 'utf8'));

const q = (s) => (s == null ? 'null' : `$cv$${String(s)}$cv$`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const settings = {
  announcement: { enabled: true, text: 'Discover digital resources for your next project.', link_label: 'Browse products', link_href: '/products' },
  company: { name: 'CODEVANTASOLUTIONSLTD', legal_name: null, registration_number: null, registered_office: null, country: null, support_email: null, phone: null, logo_path: null },
  social: { links: [] },
  homepage: { show_new_arrivals: true, show_bestsellers: true, show_featured_bundle: true, show_newsletter: true, featured_bundle_slug: 'website-starter-collection' },
  footer: { links: [] },
  seo: {
    default_title: 'CODEVANTASOLUTIONSLTD — Digital resources to build better, faster',
    default_description: 'Original website templates, UI kits, developer resources and business templates, delivered digitally by CODEVANTASOLUTIONSLTD.',
  },
  commerce: { currencies: ['INR'], default_currency: 'INR', payments_enabled: false, payment_provider_label: null, payment_methods_note: null, download_limit: 15 },
};

let sql = `-- =============================================================================
-- Initial catalogue: categories, site settings and the original starter products.
-- GENERATED by scripts/generate-seed.mjs from scripts/catalogue.mjs — edit those.
-- Products start as 'coming_soon' (shown as "In development", not purchasable).
-- =============================================================================

`;

sql += 'insert into public.categories (name, slug, description, icon, display_order) values\n';
sql += categories.map(([name, slug, desc, icon], i) => `  (${q(name)}, ${q(slug)}, ${q(desc)}, ${q(icon)}, ${(i + 1) * 10})`).join(',\n');
sql += '\non conflict (slug) do nothing;\n\n';

sql += 'insert into public.site_settings (setting_key, setting_value) values\n';
sql += Object.entries(settings).map(([k, v]) => `  (${q(k)}, ${json(v)})`).join(',\n');
sql += '\non conflict (setting_key) do nothing;\n\n';

for (const p of products) {
  const images = previews[p.slug];
  if (!images?.length) throw new Error(`No preview images for ${p.slug}; run npm run products:previews first.`);
  sql += `insert into public.products (title, slug, subtitle, short_description, description, product_type, highlights, contents,
  technical_requirements, compatibility, faq, licence_text, support_info, price, currency, category_id, preview_images,
  version, status, is_featured, seo_title, seo_description)
select ${q(p.title)}, ${q(p.slug)}, ${q(p.subtitle)}, ${q(p.short_description)}, ${q(p.description)}, ${q(p.product_type)},
  ${arr(p.highlights)},
  ${json(p.contents.map(([name, description]) => ({ name, description })))},
  ${arr(p.requirements)},
  ${arr(p.compatibility)},
  ${json(p.faq.map(([question, answer]) => ({ question, answer })))},
  ${q(p.licence_text)}, ${q(p.support_info)}, ${p.price}, 'INR', c.id,
  ${arr(images)},
  ${q(p.version)}, 'coming_soon', ${p.featured}, ${q(p.title.slice(0, 70))}, ${q(p.short_description.slice(0, 170))}
from public.categories c where c.slug = ${q(p.category)}
on conflict (slug) do nothing;\n`;
  if (p.also.length) {
    sql += `insert into public.product_categories (product_id, category_id)
select p.id, c.id from public.products p, public.categories c
where p.slug = ${q(p.slug)} and c.slug in (${p.also.map(q).join(', ')})
on conflict do nothing;\n`;
  }
  sql += '\n';
}

writeFileSync(join(root, 'supabase', 'migrations', '20261028000004_initial_catalogue.sql'), sql);
console.log(`Wrote seed migration: ${categories.length} categories, ${products.length} products, ${Object.keys(settings).length} settings.`);
